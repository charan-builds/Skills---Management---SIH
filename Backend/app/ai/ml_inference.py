def generate_explanation(
    model_type: str,
    input_data: Dict[str, Any],
    models: Optional[Dict[str, Any]] = None
) -> List[str]:
    """
    Generates non-causal, model-derived explanatory associations based on feature importance.
    """
    explanations = []
    prog = input_data.get("programme_id", "Unknown")
    district = input_data.get("district", "Unknown")
    score = input_data.get("avg_skill_score", 0.0)
    
    if model_type == "employment":
        if score >= 70.0:
            explanations.append(f"Candidate average skill score ({score}) is positively associated with employment likelihood in this model.")
        else:
            explanations.append(f"Candidate average skill score ({score}) indicates potential skill gaps that are associated with lower placement rates.")
        explanations.append(f"Training programme '{prog}' provides curriculum alignment context for employment prediction.")
        
    elif model_type == "salary":
        explanations.append(f"Skill score ({score}) and programme '{prog}' are the primary observable signals used in baseline salary estimation.")
        explanations.append("Salary estimates carry high residual variance as specific hiring firm and job role requirements remain unobserved.")
        
    elif model_type == "retention":
        salary = input_data.get("latest_salary")
        if salary is not None:
            if float(salary) >= 35000:
                explanations.append(f"Starting compensation level (${salary:,.2f}) is positively associated with 6-month retention likelihood in this model.")
            else:
                explanations.append(f"Starting compensation level (${salary:,.2f}) is associated with moderate retention in this model.")
        explanations.append(f"Programme '{prog}' in district '{district}' provides geographical and domain context for retention.")
        
    # Append mandatory non-causal statement
    explanations.append("Note: These statements reflect model-derived statistical associations and do NOT imply direct causal effects.")
    return explanations


def generate_trajectory_prediction(
    input_data: Dict[str, Any],
    models: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """
    Generates a unified decision-support trajectory connecting:
    P(employment) -> Expected Salary -> P(6-month retention).
    Explicitly handles Pre-Employment State (State A) and Post-Placement State (State B).
    """
    is_valid, errors = validate_prediction_input(input_data, require_salary=False)
    if not is_valid:
        raise ValueError(f"Input validation failed: {'; '.join(errors)}")
        
    models = models or load_inference_models()
    
    # 1. Step 1: Pre-Employment Prediction
    emp_res = predict_employment(input_data, models)
    
    # 2. Step 2: Salary Prediction (Conditional on Placement)
    sal_res = predict_salary(input_data, models)
    
    # 3. Step 3: Retention Prediction (Conditional on Placement & Known Salary)
    has_known_salary = "latest_salary" in input_data and input_data["latest_salary"] is not None
    
    if has_known_salary:
        ret_res = predict_retention(input_data, models)
        prediction_point = "post_placement"
        salary_block = {
            "available": True,
            "known_salary": float(input_data["latest_salary"]),
            "predicted_baseline_salary": sal_res["predicted_salary"],
            "prediction_context": "observed_at_placement",
            "warning": None
        }
        retention_block = {
            "available": True,
            "probability": ret_res["probability"],
            "prediction": ret_res["prediction"],
            "confidence_band": ret_res["confidence_band"],
            "prediction_context": "conditional_on_placement_and_salary"
        }
    else:
        prediction_point = "pre_employment"
        salary_block = {
            "available": True,
            "known_salary": None,
            "predicted_salary": sal_res["predicted_salary"],
            "prediction_context": "conditional_on_placement",
            "warning": sal_res["warning"]
        }
        retention_block = {
            "available": False,
            "probability": None,
            "prediction": None,
            "confidence_band": "UNAVAILABLE_PRE_PLACEMENT",
            "prediction_context": "conditional_on_placement",
            "reason": "Retention prediction requires confirmed placement salary and employment context."
        }
        
    # 4. Trajectory Stage & Qualitative Category
    # Rules for qualitative decision category:
    emp_prob = emp_res["probability"]
    ret_prob = retention_block["probability"]
    
    if emp_res["confidence_band"] == "HIGH_UNCERTAINTY_REVIEW_RECOMMENDED" or (
        retention_block["available"] and retention_block["confidence_band"] == "HIGH_UNCERTAINTY_REVIEW_RECOMMENDED"
    ):
        qualitative_category = "HUMAN REVIEW"
        trajectory_summary = "Prediction probabilities fall in the uncertainty boundary (0.40 - 0.60). Human counselor review is advised."
    elif emp_prob >= 0.60 and (ret_prob is None or ret_prob >= 0.60):
        qualitative_category = "HIGH POTENTIAL"
        trajectory_summary = "High probability of placement and strong projected retention stability."
    elif emp_prob < 0.40 or (ret_prob is not None and ret_prob < 0.40):
        qualitative_category = "LOW POTENTIAL"
        trajectory_summary = "Lower projected probability of placement or retention. Targeted skilling intervention recommended."
    else:
        qualitative_category = "MODERATE POTENTIAL"
        trajectory_summary = "Moderate placement likelihood with typical retention indicators."
        
    warnings = [SYNTHETIC_DISCLAIMER]
    if not has_known_salary:
        warnings.append(SALARY_UNCERTAINTY_WARNING)
        warnings.append("Retention probability is marked unavailable because placement salary has not been established.")
        
    unified_explanations = emp_res["explanations"] + (ret_res["explanations"] if has_known_salary else sal_res["explanations"])
    # Deduplicate non-causal disclaimer notes
    clean_explanations = [e for e in unified_explanations if not e.startswith("Note:")]
    clean_explanations.append("Note: All explanations reflect model-derived statistical associations and do NOT imply direct causal effects.")
    
    return {
        "prediction_version": models["metadata"]["version"],
        "prediction_point": prediction_point,
        "employment": {
            "probability": emp_res["probability"],
            "prediction": emp_res["prediction"],
            "confidence_band": emp_res["confidence_band"]
        },
        "salary": salary_block,
        "retention": retention_block,
        "trajectory": {
            "stage": "Placed & Active" if has_known_salary else "In Training / Pre-Placement",
            "qualitative_category": qualitative_category,
            "summary": trajectory_summary
        },
        "explanations": clean_explanations,
        "warnings": warnings,
        "provenance": models["metadata"]["provenance"]
    }
