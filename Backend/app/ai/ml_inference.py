# Safe observable feature contracts
SAFE_PRE_EMPLOYMENT_FEATURES = [
    "programme_id",
    "district",
    "avg_skill_score",
    "total_assessments"
]

SAFE_PLACEMENT_FEATURES = [
    "latest_salary"
]

FORBIDDEN_LEAKAGE_FEATURES = [
    "retained_3m",
    "retained_6m",
    "retained_12m",
    "employment_duration_days",
    "max_duration_days",
    "wage_growth_amount",
    "wage_growth_percentage",
    "employer_feedback",
    "satisfaction_score",
    "technical_deficiencies",
    "latent_ability",
    "quality_factor",
    "target_job_id"
]

SYNTHETIC_DISCLAIMER = (
    "These predictions are generated by models trained exclusively on synthetic experimental data. "
    "They serve as an advisory decision-support tool and must not be interpreted as guaranteed or real-world human outcomes."
)

SALARY_UNCERTAINTY_WARNING = (
    "Salary prediction has substantial residual uncertainty (Phase 7D Holdout R² ≈ -0.088, RMSE ≈ $3,894) "
    "and should be treated as a rough baseline estimate rather than guaranteed compensation."
)

_CACHED_MODELS: Optional[Dict[str, Any]] = None


def load_inference_models(force_reload: bool = False) -> Dict[str, Any]:
    """
    Initializes and caches the three finalized Phase 7 ML pipelines.
    Trains each pipeline on the isolated 80% development partitions using seed=42.
    """
    global _CACHED_MODELS
    if _CACHED_MODELS is not None and not force_reload:
        return _CACHED_MODELS
        
    raw_dfs = generate_synthetic_dataset(num_trainees=5000, seed=42)
    engineered = engineer_features(raw_dfs)
    
    # 1. Employment Model Pipeline (Phase 7C Best Model: RandomForestClassifier)
    X_emp, y_emp, meta_emp = build_employment_dataset(engineered, raw_dfs)
    X_train_emp, _, y_train_emp, _ = train_test_split(
        X_emp, y_emp, test_size=0.2, random_state=42, stratify=y_emp
    )
    preprocessor_emp = build_preprocessing_pipeline(
        meta_emp["categorical_features"], meta_emp["numerical_features"]
    )
    emp_pipeline = Pipeline(steps=[
        ("preprocessor", preprocessor_emp),
        ("classifier", RandomForestClassifier(
            n_estimators=100, max_depth=5, min_samples_split=2,
            min_samples_leaf=1, max_features="sqrt", random_state=42
        ))
    ])
    emp_pipeline.fit(X_train_emp, y_train_emp)
    
    # 2. Salary Model Pipeline (Phase 7D Best Model: GradientBoostingRegressor)
    X_sal, y_sal, meta_sal = build_salary_dataset(engineered, raw_dfs)
    X_train_sal, _, y_train_sal, _ = train_test_split(
        X_sal, y_sal, test_size=0.2, random_state=42
    )
    preprocessor_sal = build_preprocessing_pipeline(
        meta_sal["categorical_features"], meta_sal["numerical_features"]
    )
    sal_pipeline = Pipeline(steps=[
        ("preprocessor", preprocessor_sal),
        ("regressor", GradientBoostingRegressor(
            learning_rate=0.01, max_depth=3, min_samples_split=10,
            n_estimators=50, random_state=42
        ))
    ])
    sal_pipeline.fit(X_train_sal, y_train_sal)
    
    # 3. Retention Model Pipeline (Phase 7E Best Model: LogisticRegression)
    X_ret, y_ret, meta_ret = build_retention_dataset(engineered, raw_dfs)
    X_train_ret, _, y_train_ret, _ = train_test_split(
        X_ret, y_ret, test_size=0.2, random_state=42, stratify=y_ret
    )
    preprocessor_ret = build_preprocessing_pipeline(
        meta_ret["categorical_features"], meta_ret["numerical_features"]
    )
    ret_pipeline = Pipeline(steps=[
        ("preprocessor", preprocessor_ret),
        ("classifier", LogisticRegression(C=10.0, max_iter=1000, random_state=42))
    ])
    ret_pipeline.fit(X_train_ret, y_train_ret)
    
    _CACHED_MODELS = {
        "employment_pipeline": emp_pipeline,
        "salary_pipeline": sal_pipeline,
        "retention_pipeline": ret_pipeline,
        "metadata": {
            "version": "Phase_7F_Unified_v1.0",
            "provenance": {
                "employment_model": "RandomForestClassifier_Phase_7C (CV ROC-AUC: 0.916)",
                "salary_model": "GradientBoostingRegressor_Phase_7D (Holdout RMSE: $3,894)",
                "retention_model": "LogisticRegression_Phase_7E (Holdout ROC-AUC: 0.911)"
            },
            "synthetic_data": True
        }
    }
    return _CACHED_MODELS


def validate_prediction_input(
    input_data: Dict[str, Any],
    require_salary: bool = False
) -> Tuple[bool, List[str]]:
    """
    Validates input schema, verifies ranges, and strictly rejects forbidden leakage fields.
    """
    errors = []
    
    if not isinstance(input_data, dict):
        return False, ["Input data must be a dictionary"]
        
    # Check for forbidden leakage fields
    forbidden_present = [k for k in input_data.keys() if k in FORBIDDEN_LEAKAGE_FEATURES]
    if forbidden_present:
        errors.append(
            f"Forbidden leakage/downstream features detected: {forbidden_present}. "
            f"These fields violate temporal prediction boundaries and must not be supplied."
        )
        
    # Check required pre-employment fields
    for field in SAFE_PRE_EMPLOYMENT_FEATURES:
        if field not in input_data or input_data[field] is None:
            errors.append(f"Missing required pre-employment field: '{field}'")
            
    # Validate numerical boundaries if present
    if "avg_skill_score" in input_data and input_data["avg_skill_score"] is not None:
        try:
            score = float(input_data["avg_skill_score"])
            if not (0.0 <= score <= 100.0):
                errors.append(f"'avg_skill_score' must be between 0.0 and 100.0, got {score}")
        except (ValueError, TypeError):
            errors.append(f"'avg_skill_score' must be numeric, got {input_data['avg_skill_score']}")
            
    if "total_assessments" in input_data and input_data["total_assessments"] is not None:
        try:
            assessments = int(input_data["total_assessments"])
            if assessments < 0:
                errors.append(f"'total_assessments' must be non-negative, got {assessments}")
        except (ValueError, TypeError):
            errors.append(f"'total_assessments' must be integer, got {input_data['total_assessments']}")
            
    # Check salary validation if provided or required
    if require_salary:
        if "latest_salary" not in input_data or input_data["latest_salary"] is None:
            errors.append("Field 'latest_salary' is required for post-placement retention prediction.")
            
    if "latest_salary" in input_data and input_data["latest_salary"] is not None:
        try:
            salary = float(input_data["latest_salary"])
            if salary < 0.0:
                errors.append(f"'latest_salary' must be non-negative, got {salary}")
        except (ValueError, TypeError):
            errors.append(f"'latest_salary' must be numeric, got {input_data['latest_salary']}")
            
    return len(errors) == 0, errors


def _get_decision_band(probability: float) -> str:
    """Assigns decision-support uncertainty band to predicted probability."""
    if probability < 0.40:
        return "LOW_PROBABILITY"
    elif probability <= 0.60:
        return "HIGH_UNCERTAINTY_REVIEW_RECOMMENDED"
    else:
        return "HIGH_PROBABILITY"


def predict_employment(
    input_data: Dict[str, Any],
    models: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """
    Executes pre-employment classification inference: P(is_employed).
    """
    is_valid, errors = validate_prediction_input(input_data, require_salary=False)
    if not is_valid:
        raise ValueError(f"Input validation failed: {'; '.join(errors)}")
        
    models = models or load_inference_models()
    pipeline = models["employment_pipeline"]
    
    df = pd.DataFrame([{
        "programme_id": str(input_data["programme_id"]),
        "district": str(input_data["district"]),
        "avg_skill_score": float(input_data["avg_skill_score"]),
        "total_assessments": int(input_data["total_assessments"])
    }])
    
    prob = float(pipeline.predict_proba(df)[0, 1])
    pred = int(pipeline.predict(df)[0])
    band = _get_decision_band(prob)
    
    explanations = generate_explanation("employment", input_data, models)
    
    return {
        "probability": round(prob, 4),
        "prediction": pred,
        "confidence_band": band,
        "prediction_point": "pre_employment",
        "explanations": explanations,
        "provenance": models["metadata"]["provenance"]["employment_model"],
        "disclaimer": SYNTHETIC_DISCLAIMER
    }


def predict_salary(
    input_data: Dict[str, Any],
    models: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """
    Executes salary regression inference conditional on placement.
    """
    is_valid, errors = validate_prediction_input(input_data, require_salary=False)
    if not is_valid:
        raise ValueError(f"Input validation failed: {'; '.join(errors)}")
        
    models = models or load_inference_models()
    pipeline = models["salary_pipeline"]
    
    df = pd.DataFrame([{
        "programme_id": str(input_data["programme_id"]),
        "district": str(input_data["district"]),
        "avg_skill_score": float(input_data["avg_skill_score"]),
        "total_assessments": int(input_data["total_assessments"])
    }])
    
    predicted_salary = float(pipeline.predict(df)[0])
    predicted_salary = max(0.0, predicted_salary)
    
    explanations = generate_explanation("salary", input_data, models)
    
    return {
        "predicted_salary": round(predicted_salary, 2),
        "prediction_context": "conditional_on_placement",
        "prediction_point": "placement_intake",
        "warning": SALARY_UNCERTAINTY_WARNING,
        "explanations": explanations,
        "provenance": models["metadata"]["provenance"]["salary_model"],
        "disclaimer": SYNTHETIC_DISCLAIMER
    }


